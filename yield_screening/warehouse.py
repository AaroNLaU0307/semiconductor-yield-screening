"""DuckDB warehouse: the pipeline's source of record for extraction and aggregation.

Fab process data lives in a database. A yield analyst's work starts with a query
against a warehouse, not with a file read, so this project models that: the two raw
files are landed into a local DuckDB database and the pipeline reads from there.

**Division of labour.** SQL does extraction, filtering and aggregation. Python does
inference. There is no Mann-Whitney U or Benjamini-Hochberg in SQL, because expressing
them there would be a demonstration rather than an improvement.

**Why DuckDB rather than SQLite.** The actual access pattern is an analytical scan
across 590 sensor columns, which is what a column store is for. It installs with pip
and needs no server, so a reviewer can clone the repo and run one command.

**Provenance is unchanged.** The warehouse is built from the raw files after their
sha256 checksums are verified, and the values are copied from the parsed frame rather
than reparsed from text, so a value in the database is bit identical to the value the
original loader produced. `tests/test_warehouse.py` asserts that identity, and asserts
that the SQL drop rules agree exactly with the pandas implementation. Those two tests
are what license the claim that adding this layer moved no reported number.
"""

from __future__ import annotations

import re
from pathlib import Path

import duckdb
import numpy as np
import pandas as pd

from . import config
from .data_io import REPO_ROOT, SENSOR_PREFIX, SecomData, load_secom, verify_checksums

SQL_DIR = REPO_ROOT / "sql"
DEFAULT_DB_PATH = REPO_ROOT / "data" / "secom.duckdb"

#: Sensor identifiers are generated by this project, but anything interpolated into a
#: statement is validated anyway rather than trusted.
SENSOR_ID_PATTERN = re.compile(r"^sensor_\d{3}$")


def read_sql(name: str) -> str:
    """Return the text of a query in `sql/`, without its trailing statement separator.

    The separator is stripped so a query can also be embedded as a subquery, which is
    how `drop_rules.sql` reuses `sensor_stats.sql` instead of restating it.
    """
    text = (SQL_DIR / f"{name}.sql").read_text(encoding="utf-8").strip()
    return text[:-1].rstrip() if text.endswith(";") else text


def _thresholds() -> dict[str, object]:
    """Every placeholder value, taken from config so no threshold is hard coded in SQL."""
    return {
        "train_fraction": repr(float(config.TRAIN_FRACTION)),
        "modal_share_ceiling": repr(float(config.MODAL_SHARE_CEILING)),
        "missing_hard_ceiling": repr(float(config.MISSING_RATE_HARD_CEILING)),
        "dense_band_ceiling": repr(float(config.DENSE_BAND_CEILING)),
    }


def render(name: str, **extra: object) -> str:
    """Load a query and substitute thresholds plus any nested subqueries."""
    return read_sql(name).format(**_thresholds(), **extra)


# ---------------------------------------------------------------------------
# Building
# ---------------------------------------------------------------------------


def to_long_form(data: SecomData) -> pd.DataFrame:
    """Reshape the wide sensor matrix into (record_id, sensor_id, value) rows.

    The full grid is emitted, missing cells included as NULL, so that the long form
    round trips back to the wide matrix exactly.

    `record_id` is the row's position in the RAW file, not its position after sorting.
    That matters: ordering by (measured_at, record_id) in SQL then reproduces the
    stable timestamp sort the Python loader performs, so the partition boundary is
    identical in both.
    """
    wide = data.X.copy()
    wide.insert(0, "record_id", data.original_row.to_numpy())
    long = wide.melt(id_vars="record_id", var_name="sensor_id", value_name="value")
    return long.astype({"record_id": "int32", "sensor_id": "string", "value": "float64"})


def build_warehouse(
    db_path: Path | None = None, data: SecomData | None = None
) -> Path:
    """Create the database from the checksum verified raw files. Idempotent."""
    db_path = DEFAULT_DB_PATH if db_path is None else Path(db_path)
    if data is None:
        verify_checksums()
        data = load_secom()

    lots = pd.DataFrame(
        {
            "record_id": data.original_row.to_numpy().astype("int32"),
            "measured_at": data.timestamp.to_numpy(),
            "is_fail": data.y.to_numpy().astype(bool),
        }
    )
    measurements = to_long_form(data)

    db_path.parent.mkdir(parents=True, exist_ok=True)
    if db_path.exists():
        db_path.unlink()

    con = duckdb.connect(str(db_path))
    try:
        con.execute(read_sql("schema"))
        con.register("lots_df", lots)
        con.register("measurements_df", measurements)
        con.execute("INSERT INTO lot SELECT record_id, measured_at, is_fail FROM lots_df")
        con.execute(
            "INSERT INTO measurement SELECT record_id, sensor_id, value FROM measurements_df"
        )
        con.execute(render("partition"))
    finally:
        con.close()
    return db_path


def ensure_warehouse(db_path: Path | None = None) -> Path:
    """Build the warehouse if it is absent, so one command still runs the pipeline."""
    db_path = DEFAULT_DB_PATH if db_path is None else Path(db_path)
    if not db_path.exists():
        build_warehouse(db_path)
    return db_path


def connect(db_path: Path | None = None, read_only: bool = True):
    """Open the warehouse, building it first if needed."""
    path = ensure_warehouse(db_path)
    return duckdb.connect(str(path), read_only=read_only)


# ---------------------------------------------------------------------------
# Queries
# ---------------------------------------------------------------------------


def query(name: str, con=None, db_path: Path | None = None, **extra: object) -> pd.DataFrame:
    """Run a named query from `sql/` and return the result as a DataFrame."""
    own = con is None
    con = connect(db_path) if own else con
    try:
        return con.execute(render(name, **extra)).df()
    finally:
        if own:
            con.close()


#: Partition scopes a caller may ask for, mapped to their SQL predicate.
PARTITION_PREDICATES = {
    "train": "p.partition = 'train'",
    "holdout": "p.partition = 'holdout'",
    "all": "TRUE",
}


def _partition_predicate(partition: str) -> str:
    try:
        return PARTITION_PREDICATES[partition]
    except KeyError:
        raise ValueError(
            f"unknown partition {partition!r}, expected one of "
            f"{sorted(PARTITION_PREDICATES)}"
        ) from None


def sensor_stats_sql(partition: str = "train") -> str:
    """The sensor_stats query text, scoped to a partition."""
    return read_sql("sensor_stats").format(
        **_thresholds(), partition_predicate=_partition_predicate(partition)
    )


def sensor_stats(
    partition: str = "train", con=None, db_path: Path | None = None
) -> pd.DataFrame:
    """Per sensor coverage, distinctness, modal share and value fingerprint."""
    own = con is None
    con = connect(db_path) if own else con
    try:
        return con.execute(sensor_stats_sql(partition)).df()
    finally:
        if own:
            con.close()


def drop_rules_sql() -> str:
    """The drop rule query text. Always train scoped: a fitted rule may not see holdout."""
    return read_sql("drop_rules").format(
        **_thresholds(), sensor_stats=sensor_stats_sql("train")
    )


def drop_rules(con=None, db_path: Path | None = None) -> pd.DataFrame:
    """The declared drop rules applied in SQL, one row per sensor with its reason."""
    own = con is None
    con = connect(db_path) if own else con
    try:
        return con.execute(drop_rules_sql()).df()
    finally:
        if own:
            con.close()


def missingness_patterns(con=None, db_path: Path | None = None) -> pd.DataFrame:
    """Distinct missingness patterns among sparse band sensors, with membership."""
    return query(
        "missingness_patterns", con=con, db_path=db_path, drop_rules=drop_rules_sql()
    )


def partition_boundary(con=None, db_path: Path | None = None) -> pd.DataFrame:
    """Partition sizes, failure counts and the timestamps either side of the split."""
    return query("partition_boundary", con=con, db_path=db_path)


def monthly_failure_rate(con=None, db_path: Path | None = None) -> pd.DataFrame:
    """Failure rate by calendar month across the whole record."""
    return query("monthly_failure_rate", con=con, db_path=db_path)


def monthly_sensor_means(
    sensors: list[str], con=None, db_path: Path | None = None
) -> pd.DataFrame:
    """Monthly mean per sensor, for the drift analysis."""
    bad = [s for s in sensors if not SENSOR_ID_PATTERN.match(s)]
    if bad:
        raise ValueError(f"refusing to interpolate unexpected sensor ids: {bad}")
    sensor_list = "(" + ", ".join(f"'{s}'" for s in sensors) + ")"
    return query(
        "monthly_sensor_means", con=con, db_path=db_path, sensor_list=sensor_list
    )


# ---------------------------------------------------------------------------
# Reading back
# ---------------------------------------------------------------------------


def load_secom_from_warehouse(db_path: Path | None = None) -> SecomData:
    """Reconstruct the wide dataset from the warehouse, sorted by timestamp.

    This is the loader the pipeline uses. `tests/test_warehouse.py` asserts the result
    is identical to `load_secom()`, which is what keeps the raw files the provenance
    anchor while the database is the working source.
    """
    con = connect(db_path)
    try:
        lots = con.execute(
            "SELECT record_id, measured_at, is_fail FROM lot "
            "ORDER BY measured_at, record_id"
        ).df()
        long = con.execute(
            "SELECT record_id, sensor_id, value FROM measurement"
        ).df()
    finally:
        con.close()

    wide = long.pivot(index="record_id", columns="sensor_id", values="value")
    wide.columns.name = None
    n_sensors = wide.shape[1]
    wide = wide[[f"{SENSOR_PREFIX}{i:03d}" for i in range(n_sensors)]]
    wide = wide.reindex(lots["record_id"].to_numpy()).reset_index(drop=True)

    return SecomData(
        X=wide.astype(np.float64),
        y=pd.Series(lots["is_fail"].to_numpy().astype(int), name="__y__"),
        timestamp=pd.Series(
            pd.to_datetime(lots["measured_at"].to_numpy()), name="__timestamp__"
        ),
        original_row=pd.Series(
            lots["record_id"].to_numpy().astype(int), name="__original_row__"
        ),
    )
