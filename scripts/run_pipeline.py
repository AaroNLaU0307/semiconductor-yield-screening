def main() -> int:
    # Provenance first: the raw file checksums are verified, then the warehouse is
    # built from that verified parse. The pipeline reads from the database because that
    # is where process data lives. tests/test_warehouse.py asserts the warehouse loader
    # returns data identical to the raw loader, so the raw files stay the anchor.
    verify_checksums()
    wh.ensure_warehouse()
    data = wh.load_secom_from_warehouse()
    split = chronological_split(data.timestamp, config.TRAIN_FRACTION)

    X_train_raw = data.X.iloc[split.train_idx]
    y_train = data.y.iloc[split.train_idx].to_numpy()

    pre = Preprocessor().fit(X_train_raw)
    X_train = pre.transform(X_train_raw)

    print(
        f"split: train={split.n_train} holdout={split.n_holdout} "
        f"boundary={split.last_train_timestamp} -> {split.first_holdout_timestamp}"
    )
    print(
        f"features: {len(pre.dense_columns)} dense values + "
        f"{len(pre.indicator_groups)} indicators = {len(pre.feature_names)}"
    )

    screen, perm = phase_2_screening(X_train, y_train, pre)
    print(
        f"phase 2: {screen.n_survivors}/{screen.n_tested} survived BH at q={screen.q}, "
        f"permutation p={perm.p_value:.4f}, fallback={screen.fallback_used}"
    )

    # From here the holdout is read. Everything in DECISIONS.md is already frozen.
    X_holdout_raw = data.X.iloc[split.holdout_idx]
    y_holdout = data.y.iloc[split.holdout_idx].to_numpy()
    X_holdout = pre.transform(X_holdout_raw)

    sensors, contingency, _ = phase_3_spc(
        X_train, X_holdout, y_holdout, screen, pre, X_train_raw, X_holdout_raw
    )
    print(
        f"phase 3: charted {len(sensors)} sensors, "
        f"OOC records={contingency.n_ooc}/{len(y_holdout)}, "
        f"risk ratio={contingency.risk_ratio:.3f}, "
        f"Fisher p={contingency.p_value:.4f}"
    )
    write_timeline_data(data.timestamp, data.y.to_numpy(), split)

    metrics, threshold, sweep = phase_4_model(
        X_train, y_train, X_holdout, y_holdout, screen
    )
    primary = next(m for m in metrics if m.name.startswith("HistGradient"))
    print(
        f"phase 4: holdout PR-AUC={primary.pr_auc:.4f} "
        f"[{primary.pr_auc_ci[0]:.4f}, {primary.pr_auc_ci[1]:.4f}] "
        f"no-skill={primary.no_skill:.4f} ROC-AUC={primary.roc_auc:.4f} "
        f"recall@FPR{config.FALSE_ALARM_BUDGET_FPR}={primary.recall_at_budget:.4f}"
    )
    replication, repl_summary = phase_5_replication(
        X_train, y_train, X_holdout, y_holdout, screen
    )
    print(
        f"phase 5 (post-hoc): {repl_summary['same_sign']}/"
        f"{repl_summary['n_shortlisted']} keep effect sign on holdout, "
        f"{repl_summary['n_replicating']} replicate under BH, "
        f"median |effect| {repl_summary['median_abs_train_effect']:.3f} -> "
        f"{repl_summary['median_abs_holdout_effect']:.3f}"
    )
    print(
        "wrote reports/screening.md, reports/spc.md, reports/model.md, "
        "reports/replication.md"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
