"""Run the screening pipeline end to end and emit every generated report.

Usage, from the repository root:
    python scripts/run_pipeline.py

Deterministic: the same seed produces the same reported numbers, which is enforced by
`tests/test_determinism.py`.

Phase order follows PLAN.md. The holdout partition is not transformed or read at all
until Phase 3, and the two places that read it are declared in DECISIONS.md D12.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from yield_screening import config  # noqa: E402
from yield_screening.data_io import load_secom, verify_checksums  # noqa: E402
from yield_screening.preprocess import DROP_REASONS, Preprocessor  # noqa: E402
from yield_screening.reporting import (  # noqa: E402
    fmt_p,
    histogram_lines,
    kv_table,
    md_table,
)
from yield_screening.screening import (  # noqa: E402
    mannwhitney_screen,
    permutation_null,
)
from yield_screening.splitting import chronological_split  # noqa: E402

REPORTS = REPO_ROOT / "reports"
DASHBOARD = REPO_ROOT / "dashboard"


# ---------------------------------------------------------------------------
# Phase 2: screening
# ---------------------------------------------------------------------------


def phase_2_screening(X_train: pd.DataFrame, y_train: np.ndarray, pre: Preprocessor):
    """Screen the train partition. The holdout is not read in this phase."""
    screen = mannwhitney_screen(X_train, y_train)
    perm = permutation_null(
        X_train,
        y_train,
        observed_count=screen.n_survivors,
        n_permutations=config.N_PERMUTATIONS,
        q=config.FDR_Q,
        seed=config.RANDOM_SEED,
    )
    write_screening_report(screen, perm, pre, y_train)
    return screen, perm


def write_screening_report(screen, perm, pre: Preprocessor, y_train: np.ndarray) -> None:
    table = screen.table
    summary = perm.summary()

    table.to_csv(REPORTS / "screening_table.csv", index=False)

    n_indicator = len(pre.indicator_groups)
    n_dense = len(pre.dense_columns)

    shortlist = screen.shortlist
    display_cols = [
        "feature",
        "status",
        "effect_size_rank_biserial",
        "auc_fail_over_pass",
        "p_raw",
        "p_bh_adjusted",
    ]
    top = table.head(25)[display_cols].copy()
    top["p_raw"] = top["p_raw"].map(fmt_p)
    top["p_bh_adjusted"] = top["p_bh_adjusted"].map(fmt_p)

    groups = pd.DataFrame(
        [
            {
                "indicator column": g.column_name,
                "sensors sharing this pattern": len(g.members),
                "train missing rate": round(g.train_missing_rate, 4),
                "members": ", ".join(g.members)
                if len(g.members) <= 6
                else ", ".join(g.members[:6]) + f", and {len(g.members) - 6} more",
            }
            for g in pre.indicator_groups
        ]
    )

    # Every declared rule is listed, including the ones that fired zero times. A rule
    # that dropped nothing is a measured fact worth showing; omitting it would let a
    # reader assume work happened that did not.
    fired = (
        pre.drop_log.groupby("reason").size()
        if len(pre.drop_log)
        else pd.Series(dtype=int)
    )
    drop_summary = pd.DataFrame(
        [
            {"declared rule": reason, "sensors dropped": int(fired.get(reason, 0))}
            for reason in DROP_REASONS
        ]
    )

    verdict = screening_verdict(screen, perm)

    parts = [
        "# Screening report\n",
        "Generated by `scripts/run_pipeline.py`. Train partition only: no holdout "
        "record was read to produce anything on this page.\n",
        "## 1. Headline\n",
        verdict,
        "\n## 2. What was tested\n",
        kv_table(
            [
                ("train records", len(y_train)),
                ("train failures", int(y_train.sum())),
                ("train failure rate", f"{y_train.mean():.4f}"),
                ("dense band sensor values tested", n_dense),
                ("deduplicated missingness indicators tested", n_indicator),
                ("total tests in the BH family", screen.n_tested),
                ("test", "two sided Mann-Whitney U, tie corrected normal approximation"),
                ("effect size", "rank-biserial correlation, r = 2 * AUC - 1"),
                ("FDR method", f"Benjamini-Hochberg at q = {screen.q}"),
            ]
        ),
        "\n## 3. False discovery control result\n",
        kv_table(
            [
                ("features tested", screen.n_tested),
                ("features surviving BH", screen.n_survivors),
                (
                    "upper bound on expected false discoveries among survivors",
                    f"{screen.expected_false_discoveries:.2f}",
                ),
                ("smallest raw p that did not survive", fmt_p(screen.smallest_failing_p)),
                ("fallback triggered", screen.fallback_used),
                (
                    "features carried forward in total",
                    int(screen.table["shortlisted"].sum()),
                ),
            ]
        ),
        "\n## 4. Permutation null\n",
        "The labels were permuted "
        f"{perm.n_permutations} times and the **entire screen, BH correction "
        "included**, was rerun on each permutation. Only the labels moved, so the "
        "correlation structure among the features is preserved exactly rather than "
        "assumed. This is the check that does not depend on the dependence "
        "assumptions BH itself relies on.\n",
        kv_table(
            [
                ("permutations", perm.n_permutations),
                ("seed", perm.seed),
                ("observed survivor count", int(summary["observed"])),
                ("null mean survivor count", f"{summary['null_mean']:.2f}"),
                ("null median", f"{summary['null_median']:.0f}"),
                ("null 95th percentile", f"{summary['null_p95']:.0f}"),
                ("null maximum", f"{summary['null_max']:.0f}"),
                (
                    "permutations producing zero survivors",
                    f"{summary['null_zero_share']:.3f}",
                ),
                ("permutation p-value", fmt_p(summary["permutation_p_value"])),
            ]
        ),
        "\nNull distribution of the survivor count:\n",
        histogram_lines(perm.null_counts),
        "\n\n## 5. Ranked features\n",
        f"Top 25 of {screen.n_tested} by survival then absolute effect size. The full "
        "table is `reports/screening_table.csv`.\n",
        "`auc_fail_over_pass` is the probability that a randomly chosen failing lot "
        "exceeds a randomly chosen passing lot on that feature. 0.5 means no "
        "association.\n",
        md_table(top),
        "\n## 6. Missingness indicators\n",
        "Sparse band sensors contribute a binary not-measured indicator instead of "
        "imputed values, per DECISIONS.md D3. Identical patterns are deduplicated, so "
        f"the {int(groups['sensors sharing this pattern'].sum()) if len(groups) else 0} "
        f"sparse sensors are represented by {n_indicator} columns.\n",
        md_table(groups) if len(groups) else "No missingness indicators were emitted.",
        "\n**These are process routing features, not yield detractors.** A sensor "
        "measured for only a minority of lots usually reflects a metrology sampling "
        "plan. If such an indicator screens strongly it is evidence about how lots "
        "were routed, and it is a confound warning, not a detractor.\n",
        "\n## 7. Column filter audit\n",
        f"{len(pre.drop_log)} of the 590 raw sensors were dropped before screening, "
        "with every drop attributed to a declared rule:\n",
        md_table(drop_summary),
        "\n## 8. What this section does and does not establish\n",
        "Every ranking here is a ranking of **association**, measured on observational "
        "data from a running process with no randomised intervention. A feature high "
        "in this table is a candidate for investigation, not an established cause of "
        "yield loss. The permutation null bounds how much of the ranking could be "
        "produced by chance alone; it says nothing about whether an association that "
        "is real is also actionable.\n",
    ]

    (REPORTS / "screening.md").write_text("\n".join(parts), encoding="utf-8")

    payload = {
        "n_tested": screen.n_tested,
        "n_survivors": screen.n_survivors,
        "q": screen.q,
        "expected_false_discoveries": screen.expected_false_discoveries,
        "fallback_used": bool(screen.fallback_used),
        "permutation": {k: float(v) for k, v in summary.items()},
        "null_counts": perm.null_counts.tolist(),
        "shortlist": shortlist[display_cols].to_dict(orient="records"),
    }
    (DASHBOARD / "screening_data.json").write_text(
        json.dumps(payload, indent=2), encoding="utf-8"
    )


def screening_verdict(screen, perm) -> str:
    """Plain language headline, written to be honest in either direction."""
    p = perm.p_value
    if screen.n_survivors == 0:
        lead = (
            f"**No feature cleared the screening threshold.** Of {screen.n_tested} "
            f"features tested, zero survived Benjamini-Hochberg at q = {screen.q}."
        )
    else:
        lead = (
            f"**{screen.n_survivors} of {screen.n_tested} features cleared the "
            f"screening threshold** at Benjamini-Hochberg q = {screen.q}. BH controls "
            f"the false discovery rate at {screen.q}, which bounds the expected number "
            f"of false discoveries among those {screen.n_survivors} at about "
            f"{screen.expected_false_discoveries:.0f}."
        )

    if p <= 0.01:
        null_read = (
            f"The permutation null is decisive: across {perm.n_permutations} label "
            f"permutations, a survivor count this large arose with permutation "
            f"p = {fmt_p(p)}. The screen is finding structure that shuffling destroys."
        )
    elif p <= 0.10:
        null_read = (
            f"The permutation null is suggestive but not decisive, permutation "
            f"p = {fmt_p(p)}. Shuffled labels reproduce a count this large in roughly "
            f"{p:.0%} of permutations."
        )
    else:
        null_read = (
            f"The permutation null does not support the screen: permutation "
            f"p = {fmt_p(p)}. A survivor count this large is unremarkable among "
            "shuffled labels, so the observed count should not be read as evidence "
            "of association above the noise floor."
        )

    fallback_note = ""
    if screen.fallback_used:
        fallback_note = (
            f"\n\nBecause fewer than {config.FALLBACK_TRIGGER_BELOW} features cleared "
            f"FDR, the declared fallback carried the top {config.FALLBACK_TOP_K} "
            "features by absolute effect size into the later phases. They are labelled "
            f'"{config.FALLBACK_LABEL}" everywhere they appear, and that label is a '
            "column in the emitted data rather than prose added by hand."
        )

    return f"{lead}\n\n{null_read}{fallback_note}"


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def main() -> int:
    verify_checksums()
    data = load_secom()
    split = chronological_split(data.timestamp, config.TRAIN_FRACTION)

    X_train_raw = data.X.iloc[split.train_idx]
    y_train = data.y.iloc[split.train_idx].to_numpy()

    pre = Preprocessor().fit(X_train_raw)
    X_train = pre.transform(X_train_raw)

    print(
        f"split: train={split.n_train} holdout={split.n_holdout} "
        f"boundary={split.last_train_timestamp} -> {split.first_holdout_timestamp}"
    )
    print(
        f"features: {len(pre.dense_columns)} dense values + "
        f"{len(pre.indicator_groups)} indicators = {len(pre.feature_names)}"
    )

    screen, perm = phase_2_screening(X_train, y_train, pre)
    print(
        f"phase 2: {screen.n_survivors}/{screen.n_tested} survived BH at q={screen.q}, "
        f"permutation p={perm.p_value:.4f}, fallback={screen.fallback_used}"
    )
    print("wrote reports/screening.md, reports/screening_table.csv")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
